#!/usr/bin/env node
/**
 * Adds a `skill.meta.yaml` sidecar to every skill under skills/core/ and
 * skills/product/, declaring the project's frontmatter contract without
 * modifying the (vendored) SKILL.md body.
 *
 * Idempotent: skips skills that already have a sidecar with the same name.
 */
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();

const EXACT = {
  "karpathy-guidelines": "karpathy",
  "brainstorming": "superpowers",
  "writing-plans": "superpowers",
  "executing-plans": "superpowers",
  "subagent-driven-development": "superpowers",
  "systematic-debugging": "superpowers",
  "test-driven-development": "superpowers",
  "verification-before-completion": "superpowers",
  "receiving-code-review": "superpowers",
  "requesting-code-review": "superpowers",
  "using-git-worktrees": "superpowers",
  "finishing-a-development-branch": "superpowers",
  "dispatching-parallel-agents": "superpowers",
  "writing-skills": "superpowers",
  "using-superpowers": "superpowers",
  "ask-matt": "mattpocock",
  "code-review": "mattpocock",
  "codebase-design": "mattpocock",
  "diagnosing-bugs": "mattpocock",
  "domain-modeling": "mattpocock",
  "grill-with-docs": "mattpocock",
  "implement": "mattpocock",
  "improve-codebase-architecture": "mattpocock",
  "prototype": "mattpocock",
  "research": "mattpocock",
  "resolving-merge-conflicts": "mattpocock",
  "setup-matt-pocock-skills": "mattpocock",
  "tdd": "mattpocock",
  "to-spec": "mattpocock",
  "to-tickets": "mattpocock",
  "triage": "mattpocock",
  "wayfinder": "mattpocock",
  "wizard": "mattpocock",
  "grill-me": "mattpocock",
  "grilling": "mattpocock",
  "handoff": "mattpocock",
  "teach": "mattpocock",
  "to-questionnaire": "mattpocock",
  "wait-what": "mattpocock",
  "writing-for-agents": "mattpocock",
};

function inferSource(name) {
  if (EXACT[name]) return EXACT[name];
  if (name.startsWith("ponytail")) return "ponytail";
  return "hand-authored";
}

const TARGETS = ["skills/core", "skills/product"];

let written = 0;
let skipped = 0;

for (const dir of TARGETS) {
  const base = join(ROOT, dir);
  if (!existsSync(base)) continue;
  for (const entry of readdirSync(base)) {
    const skillDir = join(base, entry);
    if (!statSync(skillDir).isDirectory()) continue;
    const skillMd = join(skillDir, "SKILL.md");
    if (!existsSync(skillMd)) continue;

    const sidecar = join(skillDir, "skill.meta.yaml");
    if (existsSync(sidecar)) { skipped++; continue; }

    const body = readFileSync(skillMd, "utf8");
    const fm = body.match(/^---\n([\s\S]*?)\n---/);
    let vendorName = entry;
    let vendorStatus = "stable";
    if (fm) {
      const nameMatch = fm[1].match(/^name:\s*(.+)$/m);
      if (nameMatch) vendorName = nameMatch[1].trim().replace(/^['"]|['"]$/g, "");
    }

    const role = dir.endsWith("core") ? "core" : "product";
    const src = inferSource(vendorName);
    const yaml = [
      `# Auto-generated by scripts/seed-skill-metas.mjs`,
      `# Do not edit by hand unless you also own the vendor SKILL.md.`,
      `name: ${vendorName}`,
      `version: 0.1.0`,
      `source: ${src}`,
      `status: ${vendorStatus}`,
      `layer: skills`,
      `maturity: experimental`,
      `role: ${role}`,
      `vendored_skill_md: SKILL.md`,
      ``,
    ].join("\n");
    writeFileSync(sidecar, yaml, "utf8");
    written++;
  }
}

console.log(`Wrote ${written} sidecar(s); skipped ${skipped} already-present.`);
